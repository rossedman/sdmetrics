func TestRun(t *testing.T) {
	good := writeTree(t, map[string]string{"a.go": "// Package a.\npackage a\n\n// F does f.\nfunc F() {}\n"})
	bad := writeTree(t, map[string]string{"a.go": "// Package a.\npackage a\n\nfunc F() {}\n"})
	broken := writeTree(t, map[string]string{"a.go": "package"})
	for _, tc := range []struct {
		name string
		args []string
		code int
		out  string
	}{
		{"clean", []string{good}, 0, ""},
		{"problems", []string{bad}, 1, "func F has no doc comment"},
		{"clean and problems", []string{good, bad}, 1, "func F"},
		{"no args", nil, 2, ""},
		{"missing dir", []string{filepath.Join(good, "nope")}, 2, ""},
		{"parse error", []string{broken}, 2, ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			var out strings.Builder
			if code := run(tc.args, &out, io.Discard); code != tc.code {
				t.Errorf("code = %d, want %d", code, tc.code)
			}
			if !strings.Contains(out.String(), tc.out) {
				t.Errorf("stdout = %q, want substring %q", out.String(), tc.out)
			}
		})
	}
}
